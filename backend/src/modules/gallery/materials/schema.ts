import { z } from "zod";

import { translationsBodySchema } from "#shared/i18n/translations";
import { byTitle, findRepeats } from "#shared/text/titles";

/** The longest title. */
const maxTitleLength = 50;

/** The most materials the gallery may have; raise it when the artist needs more. */
export const maxMaterials = 100;

/**
 * Every material of the gallery, as the client sends it to replace them all: a saved material left
 * out is deleted. The materials come in any order, and are kept sorted by title, as the site and the
 * admin list them.
 */
export const galleryMaterialsBodySchema = z
  .strictObject({
    materials: z
      .array(
        z.strictObject({
          /** Generated by the client, so a material keeps its id while it is renamed. */
          id: z.uuid(),
          title: z.string().trim().min(1).max(maxTitleLength),
        }),
      )
      .max(maxMaterials),
    /** The titles in the other languages by id; the server makes those a person did not write. */
    translations: translationsBodySchema({}, maxTitleLength),
  })
  .superRefine(({ materials }, context) => {
    for (const { field, index } of findRepeats(materials)) {
      context.addIssue({
        code: "custom",
        message: field === "id" ? "Each id must appear once" : "Another material has this title",
        path: ["materials", index, field],
      });
    }
  })
  .transform(({ materials, translations }) => ({
    materials: materials.toSorted(byTitle),
    translations,
  }));

/**
 * The materials as stored in Firestore and as the API returns them, sorted by title. Only their
 * shape is checked: the rules above apply when the materials are saved, so tightening a rule later
 * never makes the saved materials unreadable. There are none until they are first saved.
 */
export const galleryMaterialsSchema = z.object({
  materials: z.array(z.object({ id: z.string(), title: z.string() })),
});

export type GalleryMaterials = z.infer<typeof galleryMaterialsSchema>;
